// Regenerates data/controls.csv and examples/falcon-bay-sample.json from the JS sources.
"use strict";
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const CAT = require(path.join(root, "data", "controls.js"));
const SAMPLE = require(path.join(root, "data", "sample.js"));

const cell = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
const csv = [["id", "group", "name", "description", "iso27001", "nist_csf", "evidence"].join(",")];
for (const f of CAT.families) csv.push([f.id, f.group, f.name, f.desc, f.iso.join("; "), f.csf.join("; "), f.evidence].map(cell).join(","));
fs.writeFileSync(path.join(root, "data", "controls.csv"), csv.join("\n") + "\n");

const score = {}; for (const s of CAT.statuses) score[s.id] = s.score;
let applicable = 0, sum = 0;
for (const id of Object.keys(SAMPLE.items)) { const s = score[SAMPLE.items[id].status]; if (s !== null) { applicable++; sum += s; } }
const doc = {
  schema: "uae-ia-compliance-matrix/1.0",
  framework: CAT.framework,
  catalogue: CAT.version,
  organisation: SAMPLE.organisation,
  assessment_date: SAMPLE.assessment_date,
  assessor: SAMPLE.assessor,
  compliance_score: Math.round((sum / (applicable * 4)) * 1000) / 10,
  applicable,
  controls: [],
  items: SAMPLE.items
};
fs.mkdirSync(path.join(root, "examples"), { recursive: true });
fs.writeFileSync(path.join(root, "examples", "falcon-bay-sample.json"), JSON.stringify(doc, null, 2) + "\n");
// Sub-family catalogue for the "work at sub-family level" option, generated from the crosswalk snapshots.
const { parseCsv, split } = require("./csv");
const subs = parseCsv(fs.readFileSync(path.join(root, "data", "iar-v1.1-subfamilies.csv"), "utf8"));
const isoToCsf = {};
for (const r of parseCsv(fs.readFileSync(path.join(root, "data", "iso27001-to-nist-csf.csv"), "utf8"))) isoToCsf[r.iso27001_2022] = split(r.nist_csf_2.replace(/,/g, ";"));
const subOut = subs.map((r) => {
  const annex = split(r.iso27001_2022), clauses = split(r.iso27001_clauses), prios = split(r.priority).sort();
  const csf = [];
  for (const a of annex) for (const sub of isoToCsf[a] || []) { const cat = sub.split("-")[0]; if (!csf.includes(cat)) csf.push(cat); }
  return { id: r.ref, title: r.title, description: r.family + " · mapping confidence: " + r.confidence + " · IAR priorities: " + prios.join(", "),
    priority: prios[0], priorities: prios, iso: annex.map((a) => a.replace(/^A\./, "")).concat(clauses.map((c) => "Cl. " + c)), csf: csf.sort() };
});
fs.writeFileSync(path.join(root, "data", "subfamilies.js"),
  "/* Generated by scripts/build_data.js from data/iar-v1.1-subfamilies.csv (UAE IAR v1.1 overlay of grc-control-crosswalk 1.1.0). Do not edit. MIT License. */\n" +
  "(function (root) {\n  \"use strict\";\n  var SUBFAMILIES = " + JSON.stringify(subOut, null, 1) + ";\n" +
  "  if (typeof module === \"object\" && module.exports) module.exports = SUBFAMILIES;\n  else root.UAE_IA_SUBFAMILIES = SUBFAMILIES;\n" +
  "})(typeof window !== \"undefined\" ? window : this);\n");

console.log(`wrote data/controls.csv (${CAT.families.length} rows), data/subfamilies.js (${subOut.length} sub-families) and examples/falcon-bay-sample.json (score ${doc.compliance_score}%)`);
